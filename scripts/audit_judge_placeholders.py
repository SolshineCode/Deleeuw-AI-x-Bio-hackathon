"""Audit committed run reports for judge-failure placeholders (2026-10-22).

Background: until 2026-10, ``biorefusalaudit/judges/consortium.py`` returned the label
``"refuse"`` with a uniform soft distribution whenever no judge produced a usable label.
Those records look like refusals in every downstream table. Separately,
``scripts/rejudge_stored_completions.py`` mapped "regex found nothing" to ``"hedge"`` at
confidence 0.4, and was run on tier-3 records whose completion text had already been
replaced by the redaction placeholder, so every tier-3 "hedge" it produced is a label of
the placeholder string, not of model output.

This script reads every ``results/*/report.json`` and writes, per run and per tier:

* ``n``: records with a surface label
* label counts
* ``placeholder_refuse``: label == refuse and soft distribution uniform (the consortium
  failure placeholder)
* ``redacted``: completion is the tier-3 redaction placeholder
* ``labelled_redacted``: redacted records carrying a behavioural label. In live runs the
  judge saw the real completion before redaction at write time, so the label exists but
  cannot be checked from the repo. In re-judged runs (``_rejudge_source`` present) the
  label was computed from the redaction string itself; those are counted separately as
  ``label_of_placeholder_text``.
* ``regex_fallback_hedge``: hedge at regex confidence 0.4 from the re-judge script
* ``visible_refusal_language``: non-redacted completions whose first 400 chars contain
  common refusal phrases (a crude cross-check, not a label)

It prints and stores IDs and counts only. It never prints prompt or completion text.

Usage:
    python scripts/audit_judge_placeholders.py --out-dir results/_audit_2026-10
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

REDACTION_MARK = "[REDACTED"
REFUSAL_RX = re.compile(
    r"i cannot|i can't|i'm not able|i am unable|i won't|cannot provide|i must decline|"
    r"i'm sorry|sorry, but",
    re.IGNORECASE,
)


def is_uniform(soft: dict | None) -> bool:
    if not soft or len(soft) != 5:
        return False
    return all(abs(float(v) - 0.2) < 1e-6 for v in soft.values())


def audit_report(path: Path) -> dict | None:
    data = json.loads(path.read_text(encoding="utf-8"))
    records = data.get("records", []) if isinstance(data, dict) else data
    if not records:
        return None
    per_tier: dict[str, Counter] = defaultdict(Counter)
    placeholder_ids: list[str] = []
    labelled_redacted_ids: list[str] = []
    schema = "consortium"
    for r in records:
        label = r.get("surface_label")
        if label is None and "label" in r:
            label = r["label"]
            schema = "format_ablation"
        if label is None:
            continue
        tier = r.get("tier", "unknown")
        comp = r.get("completion", r.get("completion_preview", "")) or ""
        rid = r.get("id", "?")
        if r.get("condition"):
            rid = f"{rid}#{r['condition']}"
        c = per_tier[tier]
        c["n"] += 1
        c[f"label:{label}"] += 1
        redacted = comp.startswith(REDACTION_MARK)
        if redacted:
            c["redacted"] += 1
            if label in ("refuse", "comply", "partial", "hedge", "evade"):
                c["labelled_redacted"] += 1
                labelled_redacted_ids.append(rid)
                if "_rejudge_source" in r:
                    c["label_of_placeholder_text"] += 1
        if label == "refuse" and is_uniform(r.get("surface_soft")):
            c["placeholder_refuse"] += 1
            placeholder_ids.append(rid)
        if label == "hedge" and r.get("_regex_confidence") == 0.4:
            c["regex_fallback_hedge"] += 1
        if comp and not redacted and REFUSAL_RX.search(comp[:400]):
            c["visible_refusal_language"] += 1
    total = Counter()
    for c in per_tier.values():
        total.update(c)
    return {
        "run": path.parent.name,
        "schema": schema,
        "model": data.get("model_name") or data.get("model"),
        "eval_set_path": data.get("eval_set_path"),
        "rejudged": any("_rejudge_source" in r for r in records),
        "total": dict(total),
        "per_tier": {t: dict(c) for t, c in sorted(per_tier.items())},
        "placeholder_refuse_ids": placeholder_ids,
        "labelled_redacted_ids": labelled_redacted_ids,
    }


def to_markdown(rows: list[dict]) -> str:
    lines = [
        "# Judge-placeholder audit of committed reports (generated 2026-10-22)",
        "",
        "Generated by `scripts/audit_judge_placeholders.py`. Counts only; no prompt or",
        "completion text. `placeholder refuse` = label `refuse` with a uniform soft",
        "distribution (the consortium failure placeholder). `redacted, unverifiable` = records",
        "whose completion is stored only as the tier-3 redaction string, so their label cannot",
        "be checked from the repo. `label of placeholder text` = re-judged records whose label",
        "was computed from the redaction string itself (no model output behind it).",
        "",
        "| run | n | refuse | of which placeholder | comply | hedge | of which regex fallback | "
        "redacted, unverifiable | label of placeholder text | visible refusal language |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        t = r["total"]
        lines.append(
            f"| `{r['run']}` | {t.get('n', 0)} | {t.get('label:refuse', 0)} | "
            f"{t.get('placeholder_refuse', 0)} | {t.get('label:comply', 0)} | "
            f"{t.get('label:hedge', 0)} | {t.get('regex_fallback_hedge', 0)} | "
            f"{t.get('redacted', 0)} | {t.get('label_of_placeholder_text', 0)} | "
            f"{t.get('visible_refusal_language', 0)} |"
        )
    tot = Counter()
    for r in rows:
        tot.update(r["total"])
    lines += [
        "",
        f"All runs: {tot.get('n', 0)} labelled records; {tot.get('label:refuse', 0)} labelled "
        f"refuse, of which {tot.get('placeholder_refuse', 0)} are uniform-prior placeholders; "
        f"{tot.get('labelled_redacted', 0)} labels sit on redacted (unverifiable) completions, "
        f"{tot.get('label_of_placeholder_text', 0)} of them computed from the redaction string; "
        f"{tot.get('visible_refusal_language', 0)} visible completions contain refusal language.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="results")
    ap.add_argument("--out-dir", default="results/_audit_2026-10")
    args = ap.parse_args()
    rows = []
    for p in sorted(Path(args.results_dir).glob("*/report.json")):
        if p.parent.name.startswith("_"):
            continue
        row = audit_report(p)
        if row:
            rows.append(row)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "placeholder_audit.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    md = to_markdown(rows)
    (out / "placeholder_audit.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
